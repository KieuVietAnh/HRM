$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$envFile = Join-Path $repoRoot '.env.development.local'
$marker = '# Generated by supabase/start-local.ps1; points only to the local Supabase stack.'

if (-not (Get-Command supabase -ErrorAction SilentlyContinue)) {
  throw 'Supabase CLI is not installed. Install the CLI and Docker Desktop, then rerun this script.'
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  throw 'Docker CLI is not installed. Install Docker Desktop, then rerun this script.'
}

& docker info *> $null
if ($LASTEXITCODE -ne 0) {
  throw 'Docker Engine is not running. Start Docker Desktop, then rerun this script.'
}

if (Test-Path -LiteralPath $envFile) {
  $existingEnv = Get-Content -LiteralPath $envFile -Raw
  if (-not $existingEnv.StartsWith($marker)) {
    throw '.env.development.local already exists and was not generated by this script; leaving it untouched.'
  }
}

Push-Location $repoRoot
try {
  & supabase start
  if ($LASTEXITCODE -ne 0) { throw 'Could not start the local Supabase stack.' }

  & supabase db reset --local
  if ($LASTEXITCODE -ne 0) { throw 'Could not reset the local database and load supabase/seed.sql.' }

  $statusLines = @(& supabase status --output env)
  if ($LASTEXITCODE -ne 0) { throw 'Could not read local Supabase connection settings.' }

  $urlLine = $statusLines | Where-Object { $_ -match '^(API_URL|SUPABASE_URL)=' } | Select-Object -First 1
  $keyLine = $statusLines | Where-Object { $_ -match '^(ANON_KEY|PUBLISHABLE_KEY)=' } | Select-Object -First 1
  if (-not $urlLine -or -not $keyLine) {
    throw 'Local URL/key were not present in `supabase status --output env`; inspect `supabase status` output.'
  }

  $localUrl = ($urlLine -split '=', 2)[1].Trim().Trim('"')
  $localKey = ($keyLine -split '=', 2)[1].Trim().Trim('"')
  if ($localUrl -notmatch '^https?://(127\.0\.0\.1|localhost)(:\d+)?$') {
    throw "Refusing to write a non-local Supabase URL to .env.development.local: $localUrl"
  }

  @(
    $marker,
    "VITE_SUPABASE_URL=$localUrl",
    "VITE_SUPABASE_ANON_KEY=$localKey"
  ) | Set-Content -LiteralPath $envFile -Encoding ascii

  Write-Output 'Local migrations and seed loaded. .env.local was not changed.'
  Write-Output 'Start the app with: npm.cmd run dev'
  Write-Output 'Supabase Studio: http://127.0.0.1:54323'
} finally {
  Pop-Location
}
